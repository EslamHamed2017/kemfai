#!/usr/bin/env bash
# Run every KEMFAI addon test package in its own disposable Odoo database.
# The PostgreSQL service and Odoo image are owned by the calling CI job.
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
addons_dir="${KEMFAI_CI_ADDONS_DIR:-$repo_dir/backend/addons}"
postgres_image="${KEMFAI_CI_POSTGRES_IMAGE:-postgres:16.10-alpine}"
odoo_image="${KEMFAI_CI_ODOO_IMAGE:-odoo:18.0}"
db_host="${KEMFAI_CI_DB_HOST:-127.0.0.1}"
db_port="${KEMFAI_CI_DB_PORT:-5432}"
db_user="${KEMFAI_CI_DB_USER:-odoo_ci}"
db_password="${KEMFAI_CI_DB_PASSWORD:-odoo_ci_test_only}"
run_id="${GITHUB_RUN_ID:-local}-${GITHUB_RUN_ATTEMPT:-1}-$$"
run_hash="$(printf '%s' "$run_id" | sha256sum | cut -c1-16)"
log_dir="$(mktemp -d)"
active_database=""

# Only the exact database generated by this process is ever eligible for removal.
# psql/dropdb run from the pinned PostgreSQL client image, so the GitHub runner does
# not need host client packages. The ownership check fails closed before DROP.
drop_owned_database() {
  local database="$1" owner
  case "$database" in
    kemfai_ci_*"_${run_hash}") ;;
    *) echo "FAIL cleanup: refusing non-owned database name '$database'" >&2; return 1 ;;
  esac
  owner="$(docker run --rm --network host -e PGPASSWORD="$db_password" "$postgres_image" \
    psql -XAt -v ON_ERROR_STOP=1 -h "$db_host" -p "$db_port" -U "$db_user" -d postgres \
    -c "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = '$database'")" || {
      echo "FAIL cleanup: could not inspect database '$database'" >&2
      return 1
    }
  if [ -n "$owner" ] && [ "$owner" != "$db_user" ]; then
    echo "FAIL cleanup: database '$database' is not owned by '$db_user'; preserving it" >&2
    return 1
  fi
  if [ -n "$owner" ]; then
    docker run --rm --network host -e PGPASSWORD="$db_password" "$postgres_image" \
      dropdb --force --if-exists -h "$db_host" -p "$db_port" -U "$db_user" "$database" >/dev/null || {
        echo "FAIL cleanup: could not drop database '$database'" >&2
        return 1
      }
  fi
  if [ -n "$(docker run --rm --network host -e PGPASSWORD="$db_password" "$postgres_image" \
    psql -XAt -v ON_ERROR_STOP=1 -h "$db_host" -p "$db_port" -U "$db_user" -d postgres \
    -c "SELECT 1 FROM pg_database WHERE datname = '$database'")" ]; then
    echo "FAIL cleanup: database '$database' survived DROP" >&2
    return 1
  fi
}

cleanup() {
  local status=$? cleanup_status=0
  trap - EXIT INT TERM
  set +e
  if [ -n "$active_database" ]; then
    drop_owned_database "$active_database" || cleanup_status=1
    active_database=""
  fi
  rm -rf -- "$log_dir"
  # Preserve a real test failure. A cleanup/leak failure turns success into failure.
  if [ "$status" -ne 0 ]; then exit "$status"; fi
  exit "$cleanup_status"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

mapfile -t addons < <(find "$addons_dir" -mindepth 1 -maxdepth 1 -type d -name 'kemfai_*' -printf '%f\n' | LC_ALL=C sort)
if [ "${#addons[@]}" -eq 0 ]; then
  echo "No kemfai_* addons found" >&2
  exit 1
fi

python3 "$addons_dir/test_discovery.py"

for addon in "${addons[@]}"; do
  expected_tests="$(grep -hEc '^[[:space:]]+def test_' "$addons_dir/$addon/tests"/test_*.py | awk '{n += $1} END {print n + 0}')"
  if [ "$expected_tests" -lt 1 ]; then
    echo "$addon has no discoverable test methods" >&2
    exit 1
  fi

  database="kemfai_ci_${addon#kemfai_}_${run_hash}"
  [ "${#database}" -le 63 ] || { echo "generated database name exceeds PostgreSQL limit" >&2; exit 1; }
  log="$log_dir/$addon.log"
  echo "Running $expected_tests test methods for $addon in $database"

  active_database="$database"
  set +e
  docker run --rm --network host \
    --read-only --tmpfs /tmp:rw,noexec,nosuid,size=128m \
    --tmpfs /var/lib/odoo:rw,nosuid,mode=1777,size=256m \
    -e HOST="$db_host" -e PORT="$db_port" -e USER="$db_user" -e PASSWORD="$db_password" \
    -v "$addons_dir:/mnt/extra-addons:ro" \
    --entrypoint /bin/bash "$odoo_image" -ceu \
    'odoo-bin() { exec /usr/bin/odoo "$@"; }; odoo-bin "$@"' -- \
    --database "$database" \
    --db_host "$db_host" --db_port "$db_port" --db_user "$db_user" --db_password "$db_password" \
    --addons-path=/mnt/extra-addons,/usr/lib/python3/dist-packages/odoo/addons \
    --init "$addon" --test-enable --test-tags "/$addon" \
    --without-demo=all --workers=0 --max-cron-threads=0 --http-interface=127.0.0.1 --http-port=0 --stop-after-init \
    --log-level=test 2>&1 | tee "$log"
  test_status=${PIPESTATUS[0]}
  set -e
  if [ "$test_status" -eq 0 ] && ! grep -Eq '0 failed, 0 error\(s\).* [1-9][0-9]* tests' "$log"; then
    echo "Odoo did not report a successful non-zero test run for $addon" >&2
    test_status=1
  fi
  cleanup_status=0
  drop_owned_database "$database" || cleanup_status=1
  active_database=""
  if [ "$test_status" -ne 0 ]; then exit "$test_status"; fi
  [ "$cleanup_status" -eq 0 ] || exit 1
done

echo "PASS: all ${#addons[@]} KEMFAI addons ran real Odoo tests"
